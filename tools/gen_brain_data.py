"""Generates pc/lib/BrainData.ahk from the Android SmartBrain.kt, so both bots share one brain.

Run from the repo root:  python3 tools/gen_brain_data.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KT = ROOT / "app/src/main/java/com/hyperbot/app/SmartBrain.kt"
OUT = ROOT / "pc/lib/BrainData.ahk"

src = KT.read_text(encoding="utf-8")


def strings(s):
    return re.findall(r'"((?:[^"\\]|\\.)*)"', s)


def block(name, opener):
    i = src.index(f"private val {name} = {opener}(")
    j = i + len(f"private val {name} = {opener}(")
    depth = 1
    while depth:
        c = src[j]
        if c == '"':
            j = src.index('"', j + 1)
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        j += 1
    return src[i:j]


def q(s):
    if '"' in s or "`" in s:
        sys.exit("unsupported character in: " + s)
    return '"' + s + '"'


def arr(items):
    return "[" + ", ".join(q(x) for x in items) + "]"


# topics: t("id", "g1a|g1b;g2a", "r1", "r2", emote = "x"),
topics_src = block("topics", "listOf")
topics = []
for m in re.finditer(r'\bt\((.*?)\)(?=,\s*\n|\s*\n\s*\))', topics_src, re.S):
    body = m.group(1)
    emote = None
    em = re.search(r'emote\s*=\s*"([^"]*)"', body)
    if em:
        emote = em.group(1)
        body = body[: em.start()]
    ss = strings(body)
    tid, groups, replies = ss[0], ss[1], ss[2:]
    gl = [[a.strip() for a in g.split("|")] for g in groups.split(";")]
    topics.append((tid, gl, replies, emote))

pairs = lambda name: re.findall(r'"([^"]*)"\s+to\s+"([^"]*)"', block(name, "listOf"))
slang = re.findall(r'"([^"]*)"\s+to\s+"([^"]*)"', block("slang", "mapOf"))
jokes = strings(block("jokes", "listOf"))
trivia = pairs("trivia")
riddles = pairs("riddles")
eight = strings(block("eightBall", "listOf"))
fallback = strings(block("fallback", "listOf"))
fu_src = block("followUps", "mapOf")
followups = re.findall(r'"([^"]*)"\s+to\s+listOf\(([^)]*)\)', fu_src)

lines = [
    "; AUTO-GENERATED by tools/gen_brain_data.py from the Android SmartBrain.kt. Do not edit by hand.",
    "#Requires AutoHotkey v2",
    "",
    "global BD_TOPICS := [",
]
for tid, gl, replies, emote in topics:
    g = "[" + ", ".join(arr(x) for x in gl) + "]"
    lines.append(f'    {{id: {q(tid)}, groups: {g}, replies: {arr(replies)}, emote: {q(emote or "")}}},')
lines[-1] = lines[-1].rstrip(",")
lines.append("]")
lines.append("")
lines.append("global BD_SLANG := Map(")
seen = {}
for k, v in slang:
    seen[k] = v
items = list(seen.items())
for i, (k, v) in enumerate(items):
    lines.append(f"    {q(k)}, {q(v)}" + ("," if i < len(items) - 1 else ""))
lines.append(")")
lines.append("")
lines.append("global BD_JOKES := " + arr(jokes))
lines.append("global BD_TRIVIA := [" + ", ".join(f"[{q(a)}, {q(b)}]" for a, b in trivia) + "]")
lines.append("global BD_RIDDLES := [" + ", ".join(f"[{q(a)}, {q(b)}]" for a, b in riddles) + "]")
lines.append("global BD_8BALL := " + arr(eight))
lines.append("global BD_FALLBACK := " + arr(fallback))
lines.append("global BD_FOLLOWUPS := Map(")
for i, (k, vs) in enumerate(followups):
    lines.append(f"    {q(k)}, {arr(strings(vs))}" + ("," if i < len(followups) - 1 else ""))
lines.append(")")
lines.append("")

OUT.write_text("\r\n".join(lines), encoding="utf-8-sig")
print(f"topics={len(topics)} slang={len(items)} jokes={len(jokes)} trivia={len(trivia)} riddles={len(riddles)} -> {OUT}")
